public class operadores {
    public static void main (String[] args){
    // OPERADORES
    /*
        + | incremento
        - | decremento
        / | divisao
        * | multiplicacao
        % | modulo de divisao
    */
        System.out.println(10 + 15);
        System.out.println(10 - 15);
        System.out.println(10 / 15);
        System.out.println(10 * 15);
        System.out.println(15 % 3);
    }
}
